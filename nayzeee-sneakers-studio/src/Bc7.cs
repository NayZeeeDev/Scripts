    static readonly int[] Bits = { 4, 6, 5, 7, 5, 7, 7, 5 };
    static readonly int[] AlphaBits = { 0, 0, 0, 0, 6, 8, 7, 5 };
    static readonly int[] W2 = { 0, 21, 43, 64 };
    static readonly int[] W3 = { 0, 9, 18, 27, 37, 46, 55, 64 };
    static readonly int[] W4 = { 0, 4, 9, 13, 17, 21, 26, 30, 34, 38, 43, 47, 51, 55, 60, 64 };
    const int ModeHasPBits = 0b11001011;

    struct Bits128
    {
        public ulong Low, High;
        public int Read(int n)
        {
            ulong mask = (1UL << n) - 1;
            int bits = (int)(Low & mask);
            Low >>= n;
            Low |= (High & mask) << (64 - n);
            High >>= n;
            return bits;
        }
    }

    static int Lerp(int e0, int e1, int[] w, int i) => (e0 * (64 - w[i]) + e1 * w[i] + 32) >> 6;

    /// <summary>Decodes a whole BC7 image into RGBA8.</summary>
    public static byte[] Decode(byte[] data, int offset, int width, int height)
    {
        var rgba = new byte[width * height * 4];
        int bw = (width + 3) / 4, bh = (height + 3) / 4;
        var block = new byte[64];
        for (int by = 0; by < bh; by++)
            for (int bx = 0; bx < bw; bx++)
            {
                int src = offset + (by * bw + bx) * 16;
                if (src + 16 > data.Length) return rgba;
                DecodeBlock(data, src, block);
                for (int y = 0; y < 4; y++)
                    for (int x = 0; x < 4; x++)
                    {
                        int px = bx * 4 + x, py = by * 4 + y;
                        if (px >= width || py >= height) continue;
                        System.Buffer.BlockCopy(block, (y * 4 + x) * 4, rgba, (py * width + px) * 4, 4);
                    }
            }
        return rgba;
    }

    static void DecodeBlock(byte[] src, int o, byte[] outBlock)
    {
        var bs = new Bits128 { Low = System.BitConverter.ToUInt64(src, o), High = System.BitConverter.ToUInt64(src, o + 8) };
        int mode = 0;
        while (mode < 8 && bs.Read(1) == 0) mode++;
        if (mode >= 8) { System.Array.Clear(outBlock, 0, 64); return; }

        int partition = 0, numPartitions = 1, rotation = 0, indexSelection = 0;
        if (mode == 0 || mode == 1 || mode == 2 || mode == 3 || mode == 7)
        {
            numPartitions = (mode == 0 || mode == 2) ? 3 : 2;
            partition = bs.Read(mode == 0 ? 4 : 6);
        }
        int numEndpoints = numPartitions * 2;
        if (mode == 4 || mode == 5)
        {
            rotation = bs.Read(2);
            if (mode == 4) indexSelection = bs.Read(1);
        }

        var ep = new int[6, 4];
        for (int c = 0; c < 3; c++)
            for (int e = 0; e < numEndpoints; e++) ep[e, c] = bs.Read(Bits[mode]);
        if (AlphaBits[mode] > 0)
            for (int e = 0; e < numEndpoints; e++) ep[e, 3] = bs.Read(AlphaBits[mode]);

        if (mode == 0 || mode == 1 || mode == 3 || mode == 6 || mode == 7)
        {
            for (int e = 0; e < numEndpoints; e++)
                for (int c = 0; c < 4; c++) ep[e, c] <<= 1;
            if (mode == 1)
            {
                int p0 = bs.Read(1), p1 = bs.Read(1);
                for (int c = 0; c < 3; c++) { ep[0, c] |= p0; ep[1, c] |= p0; ep[2, c] |= p1; ep[3, c] |= p1; }
            }
            else if ((ModeHasPBits & (1 << mode)) != 0)
            {
                for (int e = 0; e < numEndpoints; e++)
                {
                    int p = bs.Read(1);
                    for (int c = 0; c < 4; c++) ep[e, c] |= p;
                }
            }
        }

        int pb = (ModeHasPBits >> mode) & 1;
        for (int e = 0; e < numEndpoints; e++)
        {
            int j = Bits[mode] + pb;
            for (int c = 0; c < 3; c++) { ep[e, c] <<= 8 - j; ep[e, c] |= ep[e, c] >> j; }
            j = AlphaBits[mode] + pb;
            ep[e, 3] <<= 8 - j;
            ep[e, 3] |= ep[e, 3] >> j;
        }
        if (AlphaBits[mode] == 0)
            for (int e = 0; e < numEndpoints; e++) ep[e, 3] = 0xFF;

        int indexBitsBase = (mode == 0 || mode == 1) ? 3 : (mode == 6 ? 4 : 2);
        int indexBits2 = mode == 4 ? 3 : (mode == 5 ? 2 : 0);
        var w = indexBitsBase == 2 ? W2 : (indexBitsBase == 3 ? W3 : W4);
        var w2 = indexBits2 == 2 ? W2 : W3;

        int SetOf(int i, int j) => numPartitions == 1 ? ((i | j) != 0 ? 0 : 128) : Partitions[((numPartitions - 2) * 64 + partition) * 16 + i * 4 + j];

        var idx = new int[16];
        for (int i = 0; i < 4; i++)
            for (int j = 0; j < 4; j++)
            {
                int bits = indexBitsBase;
                if ((SetOf(i, j) & 0x80) != 0) bits--;
                idx[i * 4 + j] = bs.Read(bits);
            }

        for (int i = 0; i < 4; i++)
            for (int j = 0; j < 4; j++)
            {
                int s = SetOf(i, j) & 0x03;
                int index = idx[i * 4 + j];
                int r, g, b, a;
                int e0 = s * 2, e1 = s * 2 + 1;
                if (indexBits2 == 0)
                {
                    r = Lerp(ep[e0, 0], ep[e1, 0], w, index);
                    g = Lerp(ep[e0, 1], ep[e1, 1], w, index);
                    b = Lerp(ep[e0, 2], ep[e1, 2], w, index);
                    a = Lerp(ep[e0, 3], ep[e1, 3], w, index);
                }
                else
                {
                    int index2 = bs.Read((i | j) != 0 ? indexBits2 : indexBits2 - 1);
                    if (indexSelection == 0)
                    {
                        r = Lerp(ep[e0, 0], ep[e1, 0], w, index);
                        g = Lerp(ep[e0, 1], ep[e1, 1], w, index);
                        b = Lerp(ep[e0, 2], ep[e1, 2], w, index);
                        a = Lerp(ep[e0, 3], ep[e1, 3], w2, index2);
                    }
                    else
                    {
                        r = Lerp(ep[e0, 0], ep[e1, 0], w2, index2);
                        g = Lerp(ep[e0, 1], ep[e1, 1], w2, index2);
                        b = Lerp(ep[e0, 2], ep[e1, 2], w2, index2);
                        a = Lerp(ep[e0, 3], ep[e1, 3], w, index);
                    }
                }
                switch (rotation)
                {
                    case 1: (a, r) = (r, a); break;
                    case 2: (a, g) = (g, a); break;
                    case 3: (a, b) = (b, a); break;
                }
                int o2 = (i * 4 + j) * 4;
                outBlock[o2] = (byte)r; outBlock[o2 + 1] = (byte)g; outBlock[o2 + 2] = (byte)b; outBlock[o2 + 3] = (byte)a;
            }
    }
