#!/usr/bin/env python3
"""
Writes nayzeee-radio/shared/props_layout.lua (SPEC section 9.2) from the anchors the radio kit and the
jammer props store in their build manifests. build.py runs it after every build; run it by hand with

    python3 tools/props/gen_layout.py                 # manifests from /tmp/nzr-work/props/out + tools/props/xml
    python3 tools/props/gen_layout.py --check         # also parse the result with luac5.4 -p

Sources (newest build of each model wins): <out>/<name>/manifest.json (this machine's builds) and
tools/props/xml/<name>.json (the committed state of the last full-quality build). A radio or jammer that
has never been built keeps its placeholder values (and an empty keys list) so the client always finds
the table. Order is stable: handheld, fieldpro, military, then jammers pocket, case, heavy; keys in the
order the radio declares its parts.
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from nzprops.fsutil import FileLock, write_text  # noqa: E402

DEFAULT_WORK = "/tmp/nzr-work/props"
DEFAULT_OUT = os.path.join(DEFAULT_WORK, "out")
DEFAULT_XML = os.path.join(HERE, "xml")
DEFAULT_LUA = os.path.normpath(os.path.join(HERE, "..", "..", "shared", "props_layout.lua"))
RADIO_ORDER = ["handheld", "fieldpro", "military"]
JAMMER_ORDER = ["pocket", "case", "heavy"]
HEADER = "-- GENERATED by nayzeee-radio/tools/props/build.py (gen_layout.py) from the prop build manifests — do not edit by hand."

# used until a model has been built (same values as the hand-written placeholder)
PLACEHOLDER_RADIOS = {
    "handheld": {"skin": "px740", "w": 512, "h": 384, "center": (0.0, 0.0195, 0.030), "size": (0.036, 0.027),
                 "focus": (0.0, 0.019, 0.005), "camDist": 0.34, "tx": (0.012, 0.004, 0.092), "rx": (0.012, 0.004, 0.092)},
    "fieldpro": {"skin": "fx280", "w": 512, "h": 256, "center": (0.0, 0.0155, 0.035), "size": (0.044, 0.022),
                 "focus": (0.0, 0.015, 0.012), "camDist": 0.30, "tx": (0.016, 0.0, 0.062), "rx": (0.016, 0.0, 0.062)},
    "military": {"skin": "mx905", "w": 512, "h": 384, "center": (0.0, 0.0215, 0.032), "size": (0.042, 0.032),
                 "focus": (0.0, 0.021, 0.006), "camDist": 0.38, "tx": (0.015, 0.006, 0.098), "rx": (0.015, 0.006, 0.098)},
}
PLACEHOLDER_JAMMERS = {
    "pocket": {"size": (0.12, 0.07, 0.10), "interact": (0.0, 0.0, 0.05)},
    "case": {"size": (0.46, 0.36, 0.55), "interact": (0.0, 0.0, 0.25)},
    "heavy": {"size": (0.55, 0.40, 1.55), "interact": (0.0, 0.25, 0.45)},
}


# ---------------------------------------------------------------------------------------------
def num(x, nd=5):
    """Lua number literal: fixed point, trailing zeros trimmed, always with a decimal point."""
    v = round(float(x), nd)
    if v == 0:
        v = 0.0
    s = f"{v:.{nd}f}".rstrip("0")
    return s + "0" if s.endswith(".") else s


def vec3(v):
    return f"vec3({num(v[0])}, {num(v[1])}, {num(v[2])})"


def vec2(v):
    return f"vec2({num(v[0])}, {num(v[1])})"


def lstr(s):
    return "'" + str(s).replace("\\", "\\\\").replace("'", "\\'") + "'"


def collect(out_dirs=(DEFAULT_OUT,), xml_dir=DEFAULT_XML):
    """{model name: manifest} merged from the out folders and the committed xml folder (newest wins)."""
    found = {}
    paths = []
    for od in out_dirs:
        if od and os.path.isdir(od):
            paths += glob.glob(os.path.join(od, "*", "manifest.json"))
    if xml_dir and os.path.isdir(xml_dir):
        paths += [p for p in glob.glob(os.path.join(xml_dir, "*.json")) if not p.endswith("layout.json")]
    for p in paths:
        try:
            with open(p, encoding="utf-8") as f:
                m = json.load(f)
        except (OSError, ValueError):
            continue
        n = m.get("name")
        if not n:
            continue
        if n not in found or float(m.get("built_at") or 0) > float(found[n].get("built_at") or 0):
            found[n] = m
    return found


def _radio_block(key, m):
    lines = []
    if m is None:
        ph = PLACEHOLDER_RADIOS[key]
        lines.append(f"  {key} = {{   -- placeholder: nzr_{key} has not been built yet")
        lines.append(f"    full = 'nzr_{key}', body = 'nzr_{key}_body', skin = {lstr(ph['skin'])},")
        lines.append(f"    screen = {{ tex = 'nzr_scr', txd = 'nzr_{key}_body', w = {ph['w']}, h = {ph['h']}, center = {vec3(ph['center'])}, "
                     f"size = {vec2(ph['size'])} }},")
        lines.append(f"    focus = {vec3(ph['focus'])}, camDist = {num(ph['camDist'], 3)},")
        lines.append(f"    leds = {{ tx = {vec3(ph['tx'])}, rx = {vec3(ph['rx'])} }},")
        lines.append("    keys = {},")
        lines.append("  },")
        return lines
    a = m["anchors"]
    sc = a["screen"]
    lines.append(f"  {key} = {{")
    lines.append(f"    full = {lstr(a['full'])}, body = {lstr(a['body'])}, skin = {lstr(a['skin'])},")
    lines.append(f"    screen = {{ tex = {lstr(sc.get('tex', 'nzr_scr'))}, txd = {lstr(sc.get('txd', a['body']))}, w = {int(sc['w'])}, "
                 f"h = {int(sc['h'])}, center = {vec3(sc['center'])}, size = {vec2(sc['size'])} }},")
    lines.append(f"    focus = {vec3(a['focus'])}, camDist = {num(a['camDist'], 3)},")
    lines.append(f"    leds = {{ tx = {vec3(a['leds']['tx'])}, rx = {vec3(a['leds']['rx'])} }},")
    lines.append("    keys = {   -- stable order")
    for k in a.get("keys", []):
        s1 = (f"      {{ id = {lstr(k['id'])}, model = {lstr(k['model'])}, pos = {vec3(k['pos'])}, press = {vec3(k['press'])}, "
              f"depth = {num(k['depth'])},")
        s2 = f"        u = {vec3(k['u'])}, v = {vec3(k['v'])}, shape = {lstr(k['shape'])}, action = {lstr(k['action'])}"
        if k.get("value") is not None:
            s2 += f", value = {lstr(k['value'])}"
        if k.get("tilt") is not None:
            s2 += f", tilt = {num(k['tilt'], 2)}"
        if k.get("axis") is not None:
            s2 += f", axis = {vec3(k['axis'])}"
        if k.get("detents") is not None:
            s2 += f", detents = {int(k['detents'])}"
        lines.append(s1)
        lines.append(s2 + " },")
    lines.append("    },")
    lines.append("  },")
    return lines


def _jammer_key(name, m):
    a = m.get("anchors") or {}
    if a.get("jammer"):
        return a["jammer"]
    if name.startswith("nzr_jammer_"):
        return name[len("nzr_jammer_"):]
    return None


def layout_lua(manifests, radios=None):
    """The props_layout.lua text for these manifests. radios: radio keys to emit (default: the three
    SPEC radios; 'example' etc. only when asked)."""
    radios = list(radios or RADIO_ORDER)
    by_radio = {}
    jammers = {}
    for n, m in manifests.items():
        a = m.get("anchors") or {}
        if a.get("kind") == "radio_full":
            by_radio[a["radio"]] = m
        jk = _jammer_key(n, m)
        if jk and m.get("export", True) and a.get("kind") not in ("radio_full", "radio_body", "radio_part"):
            jammers[jk] = m
    out = [HEADER, "if not NAYZEEE_LOCK_OK then return end", "PropsLayout = {"]
    for key in radios:
        m = by_radio.get(key)
        if m is None and key not in PLACEHOLDER_RADIOS:
            continue
        out += _radio_block(key, m)
    out.append("  jammers = {")
    order = JAMMER_ORDER + sorted(k for k in jammers if k not in JAMMER_ORDER)
    for jk in order:
        m = jammers.get(jk)
        if m is None:
            if jk not in PLACEHOLDER_JAMMERS:
                continue
            ph = PLACEHOLDER_JAMMERS[jk]
            out.append(f"    {jk} = {{ model = 'nzr_jammer_{jk}', size = {vec3(ph['size'])}, interact = {vec3(ph['interact'])} }},"
                       f"   -- placeholder: not built yet")
            continue
        a = m.get("anchors") or {}
        size = m.get("dims") or [0.1, 0.1, 0.1]
        inter = a.get("interact") or [0.0, 0.0, round(float(size[2]) / 2, 4)]
        out.append(f"    {jk} = {{ model = {lstr(m['name'])}, size = {vec3(size)}, interact = {vec3(inter)} }},")
    out.append("  },")
    out.append("}")
    return "\n".join(out) + "\n"


def luac_check(path):
    """(ok, message) from `luac5.4 -p` (or luac); ok=None when no compiler is installed."""
    exe = shutil.which("luac5.4") or shutil.which("luac")
    if not exe:
        return None, "luac not found"
    r = subprocess.run([exe, "-p", path], capture_output=True, text=True)
    return r.returncode == 0, (r.stderr or r.stdout).strip()


def write_layout(manifests, path=DEFAULT_LUA, radios=None, check=True):
    """Write the layout atomically (under a lock); returns (path, ok, message)."""
    txt = layout_lua(manifests, radios)
    with FileLock(path + ".lock"):
        old = None
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                old = f.read()
        if old != txt:
            write_text(path, txt)
    ok, msg = (None, "")
    if check:
        ok, msg = luac_check(path)
    return path, ok, msg


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", action="append", default=None, help="build folder(s) with <name>/manifest.json (default the work out)")
    ap.add_argument("--xml", default=DEFAULT_XML, help="committed xml folder with <name>.json manifests ('' to skip)")
    ap.add_argument("--lua", default=DEFAULT_LUA, help="layout file to write")
    ap.add_argument("--radios", default=",".join(RADIO_ORDER), help="radio keys to emit, in order")
    ap.add_argument("--check", action="store_true", help="parse the result with luac5.4 -p")
    ap.add_argument("--print", action="store_true", help="print the Lua instead of writing it")
    args = ap.parse_args()
    mans = collect(args.out or [DEFAULT_OUT], args.xml or None)
    radios = [r.strip() for r in args.radios.split(",") if r.strip()]
    if args.print:
        sys.stdout.write(layout_lua(mans, radios))
        return
    path, ok, msg = write_layout(mans, args.lua, radios, check=args.check)
    built = sorted(m["anchors"]["radio"] for m in mans.values() if (m.get("anchors") or {}).get("kind") == "radio_full")
    print(f"[layout] {path}  (radios built: {', '.join(built) or 'none'})")
    if args.check:
        print(f"[layout] luac -p: {'ok' if ok else ('not available' if ok is None else 'FAILED ' + msg)}")
        if ok is False:
            raise SystemExit(1)


if __name__ == "__main__":
    main()
